-- Proven positions are named by what they are, not where they were found (Q993c,
-- `docs/plan-proven.md` §5.3).
--
-- A record (`runs/puzzles/<hash>.json`) calls each position by its place in the library's
-- runs, `seed-game-ply`, and `0037` keyed a person's marks (`proven_marks.position`) and a
-- try (`matches.puzzle`) by that. A re-proof from re-played runs would give the same name
-- to another position, and a person's mark would move onto it without a word. The site now
-- names a position by its content (`puzzles.name`): a digest of the core's position key
-- and what the key leaves out that can change how a game ends (the hands, the check
-- counts, a permanent colouring, the points), read off the state the engine reaches by
-- replaying the prefix. The same position reached any way, in any run, has one name.
--
-- **This renames the stored marks and tries once, as data.** The table below is every
-- position of the seven records the site offered positions from (FORMAT 4, 2026-10-20),
-- the record's old id and the name its replayed prefix reaches: `puzzles.renames` over
-- each record, all 810 replaying, no two of a game sharing a name. SQL cannot replay a
-- prefix, so the replay was done when this file was written, and
-- `tests/test_site_proven_names.py` holds this table to `puzzles.renames` over the
-- delivered records. Every mark and every try on a listed id moves to the new name on the
-- same game; the rename is one to one, so no key collides and nothing is lost. A row on an
-- id no record holds keeps its name, and is a mark the page no longer counts, as before.

create temporary table proven_names (
    game text not null,
    old  text not null,
    new  text not null,
    primary key (game, old),
    unique (game, new)
) on commit drop;

